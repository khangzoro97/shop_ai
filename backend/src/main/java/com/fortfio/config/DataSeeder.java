package com.fortfio.config;

import java.util.List;

import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

import com.fortfio.account.Account;
import com.fortfio.account.AccountRepository;
import com.fortfio.account.Role;
import com.fortfio.ai.Workflow;
import com.fortfio.auth.AuthService;
import com.fortfio.portfolio.PortfolioItem;
import com.fortfio.portfolio.PortfolioItem.Category;
import com.fortfio.portfolio.PortfolioItemRepository;

import lombok.RequiredArgsConstructor;

/**
 * Portfolio seeds are demos Fortfio made itself: the "before" photos show made-up FORTFIO
 * products generated by AI, the "after" images and video came out of the real pipeline. They are
 * marked as samples and never carry a client name, since they are not work done for a shop.
 * The files live in {@code frontend/public/portfolio}.
 */
@Component
@RequiredArgsConstructor
public class DataSeeder implements ApplicationRunner {

	private static final String FILES = "/portfolio/";
	public static final String SAMPLE_CLIENT = "Ví dụ do Chụp Xịn tạo";

	private final AccountRepository accounts;
	private final PortfolioItemRepository portfolio;
	private final AppProperties properties;
	private final PasswordEncoder passwordEncoder;

	@Override
	@Transactional
	public void run(ApplicationArguments args) {
		seedAdmin();
		if (portfolio.count() == 0) {
			portfolio.saveAll(List.of(
					sample("Serum: bàn đá, nắng sớm", Category.COSMETICS, Workflow.PRODUCT_EXACT,
							"serum-before.jpg", "serum-after.jpg", 1),
					sample("Video 10 giây có nhạc: kem dưỡng", Category.COSMETICS, Workflow.PRODUCT_VIDEO,
							null, "cream-video.mp4", 2),
					sample("Túi cói: quán cà phê mùa hè", Category.FASHION, Workflow.PRODUCT_EXACT,
							"bag-before.jpg", "bag-after.jpg", 3),
					sample("Kem dưỡng: góc spa", Category.COSMETICS, Workflow.PRODUCT_EXACT,
							"cream-before.jpg", "cream-after.jpg", 4),
					sample("Thử áo thun lên người mẫu", Category.FASHION, Workflow.VIRTUAL_TRYON,
							"tee-before.jpg", "tee-after.jpg", 5),
					sample("Sữa dưỡng thể: biển mùa hè", Category.COSMETICS, Workflow.PRODUCT_EXACT,
							"lotion-before.jpg", "lotion-after.jpg", 6)));
		}
	}

	/** The password is only used when the account is created; later changes go through the app. */
	private void seedAdmin() {
		AppProperties.Admin admin = properties.admin();
		if (!admin.configured()) {
			return;
		}
		String email = AuthService.normalizeEmail(admin.email());
		Account account = accounts.findByEmail(email)
				.orElseGet(() -> new Account(email, passwordEncoder.encode(admin.password()), "Chụp Xịn Admin", 0));
		account.setRole(Role.ADMIN);
		accounts.save(account);
	}

	private static PortfolioItem sample(String title, Category category, Workflow workflow, String before, String after,
			int order) {
		return new PortfolioItem(null, title, SAMPLE_CLIENT, category, workflow, before == null ? null : FILES + before,
				FILES + after, order, true);
	}
}
