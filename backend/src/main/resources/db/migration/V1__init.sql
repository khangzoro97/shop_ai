CREATE TABLE account (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             varchar(255)             NOT NULL UNIQUE,
    password_hash     varchar(255)             NOT NULL,
    shop_name         varchar(255)             NOT NULL,
    role              varchar(16)              NOT NULL,
    phone             varchar(16) UNIQUE,
    phone_verified_at timestamp(6) with time zone,
    credits           integer                  NOT NULL CHECK (credits >= 0),
    created_at        timestamp(6) with time zone NOT NULL
);

CREATE TABLE phone_otp (
    account_id bigint PRIMARY KEY REFERENCES account (id) ON DELETE CASCADE,
    phone      varchar(16)              NOT NULL,
    code_hash  varchar(64)              NOT NULL,
    sent_at    timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    attempts   integer                  NOT NULL
);

CREATE TABLE generation_job (
    id              uuid PRIMARY KEY,
    version         bigint                   NOT NULL,
    account_id      bigint                   NOT NULL REFERENCES account (id),
    workflow        varchar(32)              NOT NULL,
    format          varchar(16),
    style           varchar(32),
    prompt          varchar(1000),
    status          varchar(16)              NOT NULL,
    credits_charged integer                  NOT NULL,
    output_urls     varchar(4000),
    error_message   varchar(1000),
    created_at      timestamp(6) with time zone NOT NULL,
    updated_at      timestamp(6) with time zone NOT NULL
);

CREATE INDEX idx_generation_account ON generation_job (account_id, created_at);
CREATE INDEX idx_generation_status ON generation_job (status);

CREATE TABLE generation_step (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id                uuid         NOT NULL REFERENCES generation_job (id) ON DELETE CASCADE,
    kind                  varchar(16)  NOT NULL,
    model                 varchar(255) NOT NULL,
    provider_request_id   varchar(255),
    provider_status_url   varchar(1000),
    provider_response_url varchar(1000),
    output_url            varchar(1000)
);

CREATE INDEX idx_generation_step_job ON generation_step (job_id);

CREATE TABLE portfolio_item (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      varchar(255)  NOT NULL,
    client     varchar(255)  NOT NULL,
    category   varchar(16)   NOT NULL,
    workflow   varchar(32)   NOT NULL,
    before_url varchar(1000),
    after_url  varchar(1000) NOT NULL,
    sort_order integer       NOT NULL,
    sample     boolean       NOT NULL
);

-- ShedLock: ensures only one backend instance runs a scheduled task at a time.
CREATE TABLE shedlock (
    name       varchar(64)  PRIMARY KEY,
    lock_until timestamp    NOT NULL,
    locked_at  timestamp    NOT NULL,
    locked_by  varchar(255) NOT NULL
);
